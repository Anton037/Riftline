const threatMods = (threat) => ({
  hp: 1 + 0.25 * threat,
  dmg: 1 + 0.12 * threat,
  budget: 1 + 0.1 * threat,
  elite: 0.05 * threat,
  shards: 1 + 0.25 * threat,
  boss: 1 + 0.3 * threat,
});
const THREAT_NAMES = ["Wayfarer", "Trial I", "Trial II", "Trial III", "Trial IV", "Trial V"],
  pct = (mul) => Math.round((mul - 1) * 100);
const threatLevels = THREAT_NAMES.map((name, lvl) => {
  const m = threatMods(lvl);
  return {
    lvl,
    name,
    desc:
      lvl === 0
        ? "Standard expedition across all six realms."
        : `Foes +${pct(m.hp)}% HP \xB7 +${pct(m.dmg)}% damage \xB7 +${pct(m.budget)}% wave size \xB7 +${Math.round(m.elite * 100)}% elite chance \xB7 guardians +${pct(m.boss)}% HP \xB7 shards +${pct(m.shards)}%${lvl >= 3 ? " \xB7 champions roam earlier" : ""}`,
  };
});
